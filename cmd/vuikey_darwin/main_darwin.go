func boolToInt(b bool) C.int {
	if b {
		return 1
	}
	return 0
}

func syncUI() {
	c := eng.Cfg
	C.macUpdateMenuState(
		boolToInt(c.Enabled),
		C.int(c.Mode),
		boolToInt(c.SmartEnglish),
		boolToInt(c.SyllableSplit),
		boolToInt(c.ModernToneStyle),
	)
}

//export goHandleMacMouseReset
func goHandleMacMouseReset() {
	mu.Lock()
	defer mu.Unlock()
	if eng != nil {
		eng.Reset()
	}
}

//export goMenuAction
func goMenuAction(actionID C.int) {
	mu.Lock()
	defer mu.Unlock()
	if eng == nil {
		return
	}
	switch int(actionID) {
	case 1:
		eng.Cfg.Enabled = !eng.Cfg.Enabled
		eng.Reset()
	case 10:
		eng.Cfg.Mode = engine.ModeTelex
		eng.Reset()
	case 11:
		eng.Cfg.Mode = engine.ModeVNI
		eng.Reset()
	case 12:
		eng.Cfg.Mode = engine.ModeTelexVNI
		eng.Reset()
	case 20:
		eng.Cfg.SmartEnglish = !eng.Cfg.SmartEnglish
		eng.Reset()
	case 21:
		eng.Cfg.SyllableSplit = !eng.Cfg.SyllableSplit
		eng.Reset()
	case 22:
		eng.Cfg.ModernToneStyle = !eng.Cfg.ModernToneStyle
		eng.Reset()
	case 99:
		_ = config.Save(eng.Cfg)
		os.Exit(0)
	}
	_ = config.Save(eng.Cfg)
	syncUI()
}

//export goHandleMacKey
func goHandleMacKey(keyCode C.int, flags C.uint, uniChar C.uint) C.int {
	mu.Lock()
	defer mu.Unlock()
	if eng == nil {
		return 0
	}

	kc := int(keyCode)
	fl := uint(flags)

	// Hotkey: Ctrl + Space toggles Vietnamese/English
	if kc == kVK_Space && (fl&kCGEventFlagMaskControl) != 0 && (fl&kCGEventFlagMaskCommand) == 0 {
		eng.Cfg.Enabled = !eng.Cfg.Enabled
		eng.Reset()
		_ = config.Save(eng.Cfg)
		syncUI()
		return 1
	}

	// Pass through Command / Control / Option shortcuts while resetting syllable
	if (fl & (kCGEventFlagMaskCommand | kCGEventFlagMaskControl | kCGEventFlagMaskAlternate)) != 0 {
		eng.Reset()
		return 0
	}

	switch kc {
	case kVK_Delete: // Backspace
		eng.HandleBackspace()
		return 0
	case kVK_ForwardDelete: // Delete
		eng.HandleDelete()
		return 0
	case kVK_Space:
		if act, ok := eng.CheckMacroOnSpace(); ok {
			cstr := C.CString(act.CommitText + " ")
			C.macSendBackspacesAndText(C.int(act.Backspaces), cstr)
			C.free(unsafe.Pointer(cstr))
			return 1
		}
		return 0
	case kVK_Return, kVK_Tab, kVK_Escape, kVK_LeftArrow, kVK_RightArrow, kVK_UpArrow, kVK_DownArrow:
		eng.Reset()
		return 0
	}

	if uniChar == 0 {
		return 0
	}

	act := eng.ProcessKey(rune(uniChar))
	if !act.Swallow {
		return 0
	}

	cstr := C.CString(act.CommitText)
	C.macSendBackspacesAndText(C.int(act.Backspaces), cstr)
	C.free(unsafe.Pointer(cstr))
	return 1
}

